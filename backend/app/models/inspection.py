import enum
from datetime import datetime
from typing import List, Optional, TYPE_CHECKING
from sqlalchemy import String, Boolean, Float, Integer, DateTime, ForeignKey, Enum, JSON, func
from sqlalchemy.orm import Mapped, mapped_column, relationship
from backend.app.models.base import Base, UUIDMixin, TimestampMixin

if TYPE_CHECKING:
    from backend.app.models.organization import Organization
    from backend.app.models.product import Product
    from backend.app.models.user import User


class InspectionStatus(str, enum.Enum):
    """Lifecycle statuses for quality inspection runs."""
    QUEUED = "QUEUED"
    PROCESSING = "PROCESSING"
    COMPLETED = "COMPLETED"
    REQUIRES_REVIEW = "REQUIRES_REVIEW"
    FAILED = "FAILED"


class ReviewDecision(str, enum.Enum):
    """Quality manager human audit decisions."""
    CONFIRMED = "CONFIRMED"
    OVERRIDDEN = "OVERRIDDEN"


class Inspection(Base, UUIDMixin, TimestampMixin):
    """
    Primary quality inspection record connecting product, uploaded visual asset, and AI outputs.
    """
    __tablename__ = "inspections"

    organization_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("organizations.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    product_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("products.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    inspector_id: Mapped[Optional[str]] = mapped_column(
        String(36),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    status: Mapped[InspectionStatus] = mapped_column(
        Enum(InspectionStatus, name="inspection_status_enum", native_enum=False),
        nullable=False,
        default=InspectionStatus.QUEUED,
        index=True
    )
    batch_id: Mapped[Optional[str]] = mapped_column(String(36), nullable=True, index=True)
    error_message: Mapped[Optional[str]] = mapped_column(String(1000), nullable=True)

    # Relationships
    organization: Mapped["Organization"] = relationship("Organization")
    product: Mapped["Product"] = relationship("Product", back_populates="inspections")
    inspector: Mapped[Optional["User"]] = relationship("User")
    image: Mapped[Optional["InspectionImage"]] = relationship(
        "InspectionImage",
        back_populates="inspection",
        uselist=False,
        cascade="all, delete-orphan",
        lazy="selectin"
    )
    result: Mapped[Optional["InspectionResult"]] = relationship(
        "InspectionResult",
        back_populates="inspection",
        uselist=False,
        cascade="all, delete-orphan",
        lazy="selectin"
    )
    review: Mapped[Optional["InspectionReview"]] = relationship(
        "InspectionReview",
        back_populates="inspection",
        uselist=False,
        cascade="all, delete-orphan",
        lazy="selectin"
    )

    def __repr__(self) -> str:
        return f"<Inspection id={self.id} status={self.status} product_id={self.product_id}>"


class InspectionImage(Base, UUIDMixin):
    """
    Stored metadata for the uploaded high-resolution surface image.
    """
    __tablename__ = "inspection_images"

    inspection_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("inspections.id", ondelete="CASCADE"),
        unique=True,
        nullable=False,
        index=True
    )
    storage_key: Mapped[str] = mapped_column(String(512), nullable=False)
    original_filename: Mapped[str] = mapped_column(String(255), nullable=False)
    file_size_bytes: Mapped[int] = mapped_column(Integer, nullable=False)
    width: Mapped[int] = mapped_column(Integer, nullable=False)
    height: Mapped[int] = mapped_column(Integer, nullable=False)
    mime_type: Mapped[str] = mapped_column(String(100), nullable=False)
    checksum_sha256: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False
    )

    # Relationship
    inspection: Mapped["Inspection"] = relationship("Inspection", back_populates="image")


class InspectionResult(Base, UUIDMixin):
    """
    Output predictions generated by deep learning model inference.
    """
    __tablename__ = "inspection_results"

    inspection_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("inspections.id", ondelete="CASCADE"),
        unique=True,
        nullable=False,
        index=True
    )
    model_name: Mapped[str] = mapped_column(String(100), nullable=False)
    model_version: Mapped[str] = mapped_column(String(50), nullable=False)
    predicted_class: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    confidence: Mapped[float] = mapped_column(Float, nullable=False)
    is_defective: Mapped[bool] = mapped_column(Boolean, nullable=False, index=True)
    anomaly_score: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    inference_time_ms: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False
    )

    # Relationships
    inspection: Mapped["Inspection"] = relationship("Inspection", back_populates="result")
    defects: Mapped[List["Defect"]] = relationship(
        "Defect",
        back_populates="result",
        cascade="all, delete-orphan",
        lazy="selectin"
    )


class Defect(Base, UUIDMixin):
    """
    Specific defect localization region, bounding coordinates, and category.
    """
    __tablename__ = "defects"

    result_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("inspection_results.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    defect_type: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    severity: Mapped[str] = mapped_column(String(50), nullable=False, default="MEDIUM")
    bbox_x: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    bbox_y: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    bbox_w: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    bbox_h: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    confidence: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False
    )

    # Relationship
    result: Mapped["InspectionResult"] = relationship("InspectionResult", back_populates="defects")


class InspectionReview(Base, UUIDMixin):
    """
    Human quality supervisor audit trail recording confirmations or overrides.
    """
    __tablename__ = "inspection_reviews"

    inspection_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("inspections.id", ondelete="CASCADE"),
        unique=True,
        nullable=False,
        index=True
    )
    reviewer_id: Mapped[Optional[str]] = mapped_column(
        String(36),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True
    )
    decision: Mapped[ReviewDecision] = mapped_column(
        Enum(ReviewDecision, name="review_decision_enum", native_enum=False),
        nullable=False
    )
    final_class: Mapped[str] = mapped_column(String(100), nullable=False)
    is_defective: Mapped[bool] = mapped_column(Boolean, nullable=False)
    notes: Mapped[Optional[str]] = mapped_column(String(1000), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False
    )

    # Relationships
    inspection: Mapped["Inspection"] = relationship("Inspection", back_populates="review")
    reviewer: Mapped[Optional["User"]] = relationship("User")
